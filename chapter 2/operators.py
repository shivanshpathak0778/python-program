#arithmetic operators it is used to perform calculation
print(5+3)
print(5-3)
print(5*3)
print(5/3)  



#assignment operators it is used to assign value to a variable
a=5         
print(a)    

a+=3
print(a)

a-=3
print(a)



#comparison operators it is used to compare two values
a=5 
b=10
print(a==b)
print(a!=b)
print(a>b)
print(a<b)
print(a>=b)
print(a<=b)



#logical operators it is used to combine conditional statements
a= True     
b= False
print(a and b)  
print(a or b)   
print(not a) #it is used to reverse the result of a conditional statement 
